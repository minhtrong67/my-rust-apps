//! English is the key; Vietnamese is looked up from a table. Unknown strings fall back to English.

use std::{
    collections::HashMap,
    sync::{
        atomic::{AtomicBool, Ordering},
        OnceLock,
    },
};

static VI: AtomicBool = AtomicBool::new(false);

pub fn set_vi(on: bool) {
    VI.store(on, Ordering::Relaxed);
}
pub fn is_vi() -> bool {
    VI.load(Ordering::Relaxed)
}

pub fn t(s: &'static str) -> &'static str {
    if !is_vi() {
        return s;
    }
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| TABLE.iter().copied().collect()).get(s).copied().unwrap_or(s)
}

